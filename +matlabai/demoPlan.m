function plan = demoPlan
blocks = {struct('id', 'reference', 'type', 'Step', 'parameters', struct('Time', 0, 'Before', 0, 'After', 1)), ...
    struct('id', 'error', 'type', 'Sum', 'parameters', struct('Inputs', '+-')), ...
    struct('id', 'controller', 'type', 'PID', 'parameters', struct('P', 4, 'I', 2, 'D', 0.2, 'N', 100)), ...
    struct('id', 'plant', 'type', 'TransferFcn', 'parameters', struct('Numerator', 1, 'Denominator', [1 3 2])), ...
    struct('id', 'scope', 'type', 'Scope', 'parameters', struct)};
connections = {link('reference', 'error', 1), link('error', 'controller', 1), ...
    link('controller', 'plant', 1), link('plant', 'error', 2), link('plant', 'scope', 1)};
plan = struct('description', '单位阶跃 PID 闭环示例：G(s)=1/(s^2+3s+2)，P=4，I=2，D=0.2，仿真10秒。参数为演示值，未自动整定。', ...
    'stopTime', 10, 'blocks', {blocks}, 'connections', {connections}, 'output', 'plant');
end

function result = link(source, destination, port)
result = struct('from', source, 'fromPort', 1, 'to', destination, 'toPort', port);
end
