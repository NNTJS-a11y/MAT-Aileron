function text = compatibilityPrompt(release)
profile = matlabai.compatibilityProfile(release);
text = sprintf(['兼容策略：目标 %s；公共接口基线 %s。' ...
    '优先使用该基线已有的公开函数、传统名称-值参数和基础 Simulink 模块。' ...
    '不要依赖 matlab.internal.*、新版本专属语法、未确认的模块或工具箱。' ...
    '实时脚本交换使用 .mlx，不假设 .m 就是实时脚本。' ...
    '只有明确需要时才使用基线之后的新功能，并解释版本及工具箱要求、提供旧接口替代。' ...
    '目标版本不代表本机执行环境；不能虚构其他版本的执行或验证结果。'], ...
    profile.release, profile.baseline);
end
